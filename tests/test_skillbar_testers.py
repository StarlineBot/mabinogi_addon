def test_case_list_covers_all_large_screenshots():
    large = []
    for path in DATA.rglob("*.png"):
        img = image_io.imread(path, cv2.IMREAD_COLOR)
        if img is not None and img.shape[1] >= 1200:
            large.append(path.relative_to(DATA).as_posix())
    assert sorted(large) == sorted(name for name, _, _ in CASES)


@pytest.mark.parametrize("name,expected,old_found", CASES, ids=[c[0] for c in CASES])
def test_tester_screenshot(name, expected, old_found):
    img = image_io.imread(DATA / name, cv2.IMREAD_COLOR)
    trace = {}
    box = locate_skillbar(img, None, trace)
    assert (tuple(box) if box else None) == expected, trace.get("rejection")
    if expected is not None:
        assert expected[2:] == (1168, 89)  # 해상도와 무관한 고정 크기

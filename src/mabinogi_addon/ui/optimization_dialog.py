"""Creator alpha controls; construction/rendering never changes OS settings."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QCheckBox, QComboBox, QDialog, QFormLayout,
    QHBoxLayout, QLabel, QPushButton, QSpinBox, QTabWidget, QVBoxLayout, QWidget)
from .widgets import FeatureHeader


class OptimizationDialog(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle('게임 최적화 · 제작자 알파')
        self.resize(720, 650)
        root = QVBoxLayout(self)
        self.tabs = QTabWidget()
        root.addWidget(self.tabs)
        page = QWidget()
        body = QVBoxLayout(page)
        body.addWidget(FeatureHeader('게임 최적화', '선택한 CPU 배치와 네트워크 설정을 적용하고, 변경 전 값으로 되돌릴 수 있어요.'))
        self.cpu_info = QLabel('환경 확인을 누르면 CPU 구조와 네트워크 어댑터를 읽어요.')
        self.cpu_info.setWordWrap(True)
        body.addWidget(self.cpu_info)
        self.cpu = QCheckBox('게임·백그라운드 CPU 배치')
        self.cpu.setChecked(True)
        body.addWidget(self.cpu)
        form = QFormLayout()
        self.split = QComboBox()
        self.split.addItem('CPU 구조를 먼저 확인해 주세요.', None)
        form.addRow('물리 코어 배분', self.split)
        self.adapter = QComboBox()
        self.adapter.addItem('네트워크 어댑터를 선택해 주세요.', None)
        form.addRow('네트워크 어댑터', self.adapter)
        body.addLayout(form)
        self.tcp = QCheckBox('패스트핑 · TCP 자동 조정 Normal')
        self.rss = QCheckBox('RSS 수신 처리를 백그라운드 코어에 배치')
        body.addWidget(self.tcp)
        body.addWidget(self.rss)
        self.notice = QLabel('TCP·RSS는 다른 앱의 통신에도 영향을 줄 수 있고 관리자 권한·재연결이 필요해요.\n게임 실행 중 시작하면 네트워크는 미루고 CPU만 적용해요.\n성능이 좋아졌다는 의미는 아니에요. 효과는 별도 계측으로 비교해 주세요.')
        self.notice.setWordWrap(True)
        body.addWidget(self.notice)
        self.inspect = QPushButton('환경 확인')
        self.start = QPushButton('최적화 시작')
        self.stop = QPushButton('중단 · CPU 원복')
        self.restore = QPushButton('네트워크 원복')
        row = QHBoxLayout()
        for button in (self.inspect, self.start, self.stop, self.restore):
            row.addWidget(button)
        body.addLayout(row)
        self.status = QLabel('시작 전 · 시스템 설정을 변경하지 않았어요.')
        self.status.setWordWrap(True)
        body.addWidget(self.status)
        self.results = QLabel('')
        self.results.setWordWrap(True)
        body.addWidget(self.results)
        body.addStretch()
        self.tabs.addTab(page, '최적화')
        page = QWidget()
        body = QVBoxLayout(page)
        body.addWidget(FeatureHeader('FPS 측정', '마비노기의 프레임을 측정해 현재 FPS를 보여줘요.'))
        hint = QLabel('측정 시작을 누르면 등록한 게임창을 대상으로 프레임을 수집해요.\n게임의 제출 프레임 기준이며, 모니터에 실제 표시된 FPS·통신 지연과는 달라요.')
        hint.setWordWrap(True)
        body.addWidget(hint)
        permission_hint = QLabel('Windows 권한이 부족하면 측정을 시작하지 못할 수 있어요. 자동으로 관리자 권한을 요청하지 않아요.')
        permission_hint.setWordWrap(True)
        body.addWidget(permission_hint)
        self.source = QComboBox()
        self.source.addItem('렌더링 대상: 측정 준비 중', None)
        body.addWidget(self.source)
        row = QHBoxLayout()
        self.frames_start = QPushButton('FPS 측정 시작')
        self.frames_stop = QPushButton('측정 중단')
        self.lock = QCheckBox('위치 잠금')
        self.lock.setChecked(True)
        for widget in (self.frames_start, self.frames_stop, self.lock): row.addWidget(widget)
        body.addLayout(row)
        scale_row = QFormLayout()
        self.scale = QSpinBox()
        self.scale.setRange(50,300)
        self.scale.setValue(100)
        self.scale.setSuffix(' %')
        scale_row.addRow('표시 배율',self.scale)
        body.addLayout(scale_row)
        self.frames_status = QLabel('중단됨 · 측정값 없음')
        self.frames_status.setWordWrap(True)
        body.addWidget(self.frames_status)
        body.addWidget(QLabel('앱을 다시 실행하면 자동으로 측정하지 않아요. 전투 보조 일시정지는 FPS 표시만 숨겨요.'))
        body.addStretch()
        self.tabs.addTab(page, 'FPS 측정')
